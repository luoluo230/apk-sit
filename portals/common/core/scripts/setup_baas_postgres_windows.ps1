#Requires -Version 5.1
param(
    [string]$DbUser = "apk_baas",
    [string]$DbPassword = "apk_baas_dev",
    [string]$DbName = "apk_baas",
    [int]$Port = 5432,
    [switch]$SkipInstall
)

$ErrorActionPreference = "Stop"
$core = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $PSScriptRoot "baas-database.env"
$databaseUrl = "postgresql://${DbUser}:${DbPassword}@127.0.0.1:${Port}/${DbName}"

function Find-PsqlPath {
    $pgRoot = "C:\Program Files\PostgreSQL"
    if (Test-Path $pgRoot) {
        $hits = Get-ChildItem -Path $pgRoot -Recurse -Filter "psql.exe" -ErrorAction SilentlyContinue |
            Sort-Object FullName -Descending
        if ($hits) { return $hits[0].FullName }
    }
    $cmd = Get-Command psql -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    return $null
}

function Test-PostgresPortOpen {
    param([int]$P = 5432)
    try {
        return (Test-NetConnection -ComputerName 127.0.0.1 -Port $P -WarningAction SilentlyContinue).TcpTestSucceeded
    } catch { return $false }
}

Write-Host "=== BaaS PostgreSQL (Windows native) ===" -ForegroundColor Cyan

if (-not $SkipInstall -and -not (Test-PostgresPortOpen -P $Port)) {
    $winget = Get-Command winget -ErrorAction SilentlyContinue
    if (-not $winget) { throw "PostgreSQL not listening and winget unavailable. Install PostgreSQL 17 manually." }
    Write-Host "(pg) installing PostgreSQL 17 via winget..." -ForegroundColor Yellow
    & winget install --id PostgreSQL.PostgreSQL.17 -e --accept-package-agreements --accept-source-agreements
    Start-Sleep -Seconds 8
    $svc = Get-Service -Name "postgresql*" -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($svc -and $svc.Status -ne "Running") {
        Write-Host "(pg) starting service $($svc.Name)..." -ForegroundColor Yellow
        Start-Service $svc.Name
    }
}

$deadline = (Get-Date).AddMinutes(5)
while (-not (Test-PostgresPortOpen -P $Port) -and (Get-Date) -lt $deadline) {
    Write-Host "(pg) waiting for port $Port..." -ForegroundColor DarkGray
    Start-Sleep -Seconds 3
}
if (-not (Test-PostgresPortOpen -P $Port)) {
    throw "PostgreSQL is not listening on 127.0.0.1:$Port"
}

$psql = Find-PsqlPath
if (-not $psql) { throw "psql.exe not found. Install PostgreSQL first." }
Write-Host "(pg) psql=$psql" -ForegroundColor DarkGray

$sqlLines = @(
    "DO `$`$ BEGIN",
    "  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '$DbUser') THEN",
    "    CREATE ROLE $DbUser LOGIN PASSWORD '$DbPassword';",
    "  END IF;",
    "END `$`$;",
    "SELECT 'CREATE DATABASE $DbName OWNER $DbUser'",
    "WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '$DbName')\gexec",
    "GRANT ALL PRIVILEGES ON DATABASE $DbName TO $DbUser;"
)
$sqlFile = Join-Path $env:TEMP "baas_pg_setup.sql"
Set-Content -Path $sqlFile -Value ($sqlLines -join "`n") -Encoding UTF8

$env:PGPASSWORD = "postgres"
& $psql -h 127.0.0.1 -p $Port -U postgres -d postgres -f $sqlFile
Remove-Item $sqlFile -ErrorAction SilentlyContinue

Push-Location $core
Write-Host "(pg) pip install psycopg2-binary if needed..." -ForegroundColor DarkGray
& py -3 -m pip install psycopg2-binary -q
$env:DATABASE_URL = $databaseUrl
& py -3 -c "from models.db import init_db; init_db(); print('init_db OK on PostgreSQL')"
if ($LASTEXITCODE -ne 0) {
    Pop-Location
    throw "init_db failed. If postgres superuser password is not 'postgres', create role/db manually then re-run with -SkipInstall."
}
Pop-Location

$content = @(
    "# Auto-generated by setup_baas_postgres_windows.ps1",
    "DATABASE_URL=$databaseUrl"
)
Set-Content -Path $envFile -Value ($content -join "`n") -Encoding UTF8

Write-Host ""
Write-Host "=== PostgreSQL ready for BaaS ===" -ForegroundColor Green
Write-Host "  DATABASE_URL written to the local env file (value redacted)"
Write-Host "  Env file:     $envFile"
Write-Host ""
Write-Host "Start BaaS:" -ForegroundColor Cyan
Write-Host "  cd $core"
Write-Host "  ./scripts/run_baas_server.ps1"
Write-Host ""
Write-Host "View tables:" -ForegroundColor Cyan
Write-Host "  psql -h 127.0.0.1 -p $Port -U $DbUser -d $DbName"
Write-Host "  then: \dt baas_*"
